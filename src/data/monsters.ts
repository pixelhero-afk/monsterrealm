export function getMonsterFamily(familyId: string): MonsterFamily | undefined {
  return MONSTER_FAMILIES[familyId];
}

export function getMonsterVariant(variantId: string): MonsterVariant | undefined {
  if (variantId === 'var_shadowstalker_umbral') return MONSTER_VARIANTS['var_shadowstalker_grass'];
  if (variantId === 'var_shadowstalker_phantom') return MONSTER_VARIANTS['var_shadowstalker_light'];
  return MONSTER_VARIANTS[variantId];
}

export function getAllVariants(): MonsterVariant[] {
  const seen = new Set<string>();
  const list: MonsterVariant[] = [];
  for (const v of Object.values(MONSTER_VARIANTS)) {
    if (!seen.has(v.variantId)) {
      seen.add(v.variantId);
      list.push(v);
    }
  }
  return list;
}
